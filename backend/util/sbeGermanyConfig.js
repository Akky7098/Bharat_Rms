/* =========================================================
   GET ONE GRADE CONFIG
========================================================= */

const getSbeGradeConfig = (
  grade
) => {
  const cleanGrade =
    String(grade || "").trim();

  if (!cleanGrade) {
    throw new Error(
      "SBE Germany grade is required"
    );
  }

  const config =
    SBE_GRADE_CONFIG[
      cleanGrade
    ];

  if (!config) {
    throw new Error(
      `SBE Germany configuration not found for grade ${cleanGrade}`
    );
  }

  /*
   * Deep clone so callers cannot accidentally
   * modify the master configuration.
   */
  return JSON.parse(
    JSON.stringify(config)
  );
};


/* =========================================================
   GET AVAILABLE GRADES

   Frontend dropdown should use ONLY this.
========================================================= */

const getSbeGrades = () => {
  return Object.keys(
    SBE_GRADE_CONFIG
  ).map((grade) => ({
    value: grade,
    label: grade,
  }));
};


