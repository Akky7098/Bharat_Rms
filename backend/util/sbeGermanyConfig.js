/* =========================================================
   BASIC HELPERS
========================================================= */

const cleanText = (
  value
) => {
  if (
    value === null ||
    value === undefined
  ) {
    return "";
  }

  return String(
    value
  ).trim();
};


const cloneData = (
  value
) => {
  return JSON.parse(
    JSON.stringify(
      value
    )
  );
};


const isPlainObject = (
  value
) => {
  return (
    value !== null &&
    typeof value ===
      "object" &&
    !Array.isArray(
      value
    )
  );
};


/* =========================================================
   GET ONE GRADE CONFIG
========================================================= */

const getSbeGradeConfig = (
  grade
) => {
  const cleanGrade =
    cleanText(
      grade
    );

  if (
    !cleanGrade
  ) {
    throw new Error(
      "SBE Germany grade is required"
    );
  }

  const config =
    SBE_GRADE_CONFIG[
      cleanGrade
    ];

  if (
    !config
  ) {
    throw new Error(
      `SBE Germany configuration not found for grade ${cleanGrade}`
    );
  }

  /*
   * Deep clone so callers cannot accidentally
   * modify master configuration.
   */
  return cloneData(
    config
  );
};


