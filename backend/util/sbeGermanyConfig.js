/* =========================================================
   VALIDATE USER-EDITABLE SBE DATA

   Backend validation is important.
   Frontend validation alone is not enough.
========================================================= */

const validateSbeEditableFields = (
  payload = {}
) => {
  const errors = [];

  const grade =
    String(
      payload.grade || ""
    ).trim();

  const customerName =
    String(
      payload.customerName ||
        ""
    ).trim();

  const quantity =
    String(
      payload.quantity ||
        payload.pcs ||
        ""
    ).trim();

  const dimension =
    String(
      payload.dimension ||
        payload.size ||
        ""
    ).trim();


  /* =======================================================
     GRADE
  ======================================================= */

  if (!grade) {
    errors.push(
      "Grade is required"
    );
  } else if (
    !SBE_GRADE_CONFIG[
      grade
    ]
  ) {
    errors.push(
      `Invalid SBE Germany grade: ${grade}`
    );
  }


  /* =======================================================
     CUSTOMER
  ======================================================= */

  if (!customerName) {
    errors.push(
      "Customer Name is required"
    );
  }


  /* =======================================================
     QUANTITY
  ======================================================= */

  if (!quantity) {
    errors.push(
      "Quantity is required"
    );
  } else {
    const numericQuantity =
      Number(quantity);

    if (
      Number.isNaN(
        numericQuantity
      ) ||
      numericQuantity <= 0
    ) {
      errors.push(
        "Quantity must be greater than 0"
      );
    }
  }


  /* =======================================================
     DIMENSION
  ======================================================= */

  if (!dimension) {
    errors.push(
      "Dimension is required"
    );
  }


  if (errors.length) {
    throw new Error(
      errors.join(", ")
    );
  }

  return true;
};


