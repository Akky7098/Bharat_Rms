/* =========================================================
   VALIDATE COMPLETE EDITABLE DATA

   Kept for backward compatibility.

   Used when all four create fields must exist:
   - grade
   - customerName
   - quantity
   - dimension
========================================================= */

const validateSbeEditableFields = (
  payload = {}
) => {
  const errors = [];

  const grade =
    cleanText(
      payload.grade
    );

  const customerName =
    cleanText(
      payload.customerName
    );

  /*
   * Keep support for old pcs alias.
   */
  const quantity =
    cleanText(
      payload.quantity ??
        payload.pcs
    );

  /*
   * Keep support for old size alias.
   */
  const dimension =
    cleanText(
      payload.dimension ??
        payload.size
    );


  /* =======================================================
     GRADE
  ======================================================= */

  if (
    !grade
  ) {
    errors.push(
      "Grade is required"
    );
  } else if (
    !SBE_GRADE_CONFIG[
      grade
    ]
  ) {
    errors.push(
      `Invalid SBE Germany grade: ${grade}`
    );
  }


  /* =======================================================
     CUSTOMER
  ======================================================= */

  if (
    !customerName
  ) {
    errors.push(
      "Customer Name is required"
    );
  }


  /* =======================================================
     QUANTITY
  ======================================================= */

  if (
    !quantity
  ) {
    errors.push(
      "Quantity is required"
    );
  } else {
    const numericQuantity =
      Number(
        quantity
      );

    if (
      !Number.isFinite(
        numericQuantity
      ) ||
      numericQuantity <= 0
    ) {
      errors.push(
        "Quantity must be greater than 0"
      );
    }
  }


  /* =======================================================
     DIMENSION
  ======================================================= */

  if (
    !dimension
  ) {
    errors.push(
      "Dimension is required"
    );
  }


  if (
    errors.length
  ) {
    throw new Error(
      errors.join(
        ", "
      )
    );
  }

  return true;
};


/* =========================================================
   CHECK ALLOWED REQUEST FIELDS
========================================================= */

const validateAllowedFields = (
  payload,
  allowedFields,
  actionName
) => {
  if (
    !isPlainObject(
      payload
    )
  ) {
    throw new Error(
      `Invalid SBE Germany ${actionName} payload`
    );
  }

  const allowed =
    new Set(
      allowedFields
    );

  const restrictedFields =
    Object.keys(
      payload
    ).filter(
      (
        field
      ) =>
        !allowed.has(
          field
        )
    );

  if (
    restrictedFields.length >
    0
  ) {
    throw new Error(
      `Restricted SBE Germany field(s): ${restrictedFields.join(
        ", "
      )}`
    );
  }

  return true;
};


/* =========================================================
   VALIDATE CREATE PAYLOAD

   Frontend is allowed to send ONLY:

   {
     mtcProvider: "sbe_germany",
     grade: "...",
     customerName: "...",
     quantity: "...",
     dimension: "..."
   }

   Everything else is generated/rebuilt by backend.
========================================================= */

const validateSbeCreatePayload = (
  payload = {}
) => {
  validateAllowedFields(
    payload,

    [
      "mtcProvider",
      "grade",
      "customerName",
      "quantity",
      "dimension",
    ],

    "create"
  );


  /* =======================================================
     PROVIDER
  ======================================================= */

  if (
    payload.mtcProvider !==
      undefined &&
    cleanText(
      payload.mtcProvider
    ).toLowerCase() !==
      SBE_PROVIDER
  ) {
    throw new Error(
      "Invalid MTC provider for SBE Germany certificate"
    );
  }


  /* =======================================================
     COMPLETE CREATE VALIDATION
  ======================================================= */

  validateSbeEditableFields(
    {
      grade:
        payload.grade,

      customerName:
        payload.customerName,

      quantity:
        payload.quantity,

      dimension:
        payload.dimension,
    }
  );


  /*
   * Confirm grade config can actually
   * be loaded.
   */
  getSbeGradeConfig(
    payload.grade
  );


  return true;
};


/* =========================================================
   VALIDATE UPDATE PAYLOAD

   After creation user may change ONLY:

   - customerName
   - quantity
   - dimension

   Grade cannot change.
   Generated values cannot change.
   Controlled values cannot change.
========================================================= */

const validateSbeUpdatePayload = (
  payload = {}
) => {
  validateAllowedFields(
    payload,

    [
      "mtcProvider",
      "customerName",
      "quantity",
      "dimension",
    ],

    "update"
  );


  /* =======================================================
     PROVIDER
  ======================================================= */

  if (
    payload.mtcProvider !==
      undefined &&
    cleanText(
      payload.mtcProvider
    ).toLowerCase() !==
      SBE_PROVIDER
  ) {
    throw new Error(
      "MTC provider cannot be changed"
    );
  }


  /* =======================================================
     CUSTOMER NAME
  ======================================================= */

  if (
    payload.customerName !==
    undefined
  ) {
    const customerName =
      cleanText(
        payload.customerName
      );

    if (
      !customerName
    ) {
      throw new Error(
        "Customer Name cannot be empty"
      );
    }
  }


  /* =======================================================
     QUANTITY
  ======================================================= */

  if (
    payload.quantity !==
    undefined
  ) {
    const quantity =
      cleanText(
        payload.quantity
      );

    if (
      !quantity
    ) {
      throw new Error(
        "Quantity cannot be empty"
      );
    }

    const numericQuantity =
      Number(
        quantity
      );

    if (
      !Number.isFinite(
        numericQuantity
      ) ||
      numericQuantity <= 0
    ) {
      throw new Error(
        "Quantity must be greater than 0"
      );
    }
  }


  /* =======================================================
     DIMENSION
  ======================================================= */

  if (
    payload.dimension !==
    undefined
  ) {
    const dimension =
      cleanText(
        payload.dimension
      );

    if (
      !dimension
    ) {
      throw new Error(
        "Dimension cannot be empty"
      );
    }
  }


  return true;
};


